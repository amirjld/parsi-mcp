import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { createServer } from "../src/server.js";

interface Prop { type?: string; enum?: unknown[]; description?: string }

/** Builds TOOLS.md from the tools actually registered on the server. */
export async function buildToolsMarkdown(): Promise<string> {
  const server = createServer();
  const client = new Client({ name: "docs", version: "0.0.0" });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(a), client.connect(b)]);
  const { tools } = await client.listTools();
  await client.close();
  const lines = [
    "# Tool catalog",
    "",
    "<!-- Generated by `npm run docs:tools` from the server's registered tools. Do not edit by hand. -->",
    "",
    `parsi-mcp exposes **${tools.length} tools**. All run offline.`,
    "",
    "| Tool | What it does | Parameters |",
    "| --- | --- | --- |",
  ];
  for (const t of tools) {
    const props = ((t.inputSchema as { properties?: Record<string, Prop> }).properties ?? {});
    const required = new Set((t.inputSchema as { required?: string[] }).required ?? []);
    const params = Object.entries(props).map(([k, v]) => {
      const type = v.enum ? v.enum.map((e) => JSON.stringify(e)).join(" \\| ") : v.type ?? "object";
      return `\`${k}${required.has(k) ? "" : "?"}\`: ${type}`;
    });
    const desc = (t.description ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
    lines.push(`| \`${t.name}\` | ${desc} | ${params.join("<br>") || "none"} |`);
  }
  lines.push("");
  return lines.join("\n");
}
